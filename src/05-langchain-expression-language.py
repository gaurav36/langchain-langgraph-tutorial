# First chain generates a story
story_prompt = ChatPromptTemplate.from_template("Write a short story about {topic}")
story_chain = (story_prompt | llm | StrOutputParser())

# Second chain analyzes the story
analysis_prompt = ChatPromptTemplate.from_template("Analyze the following story's mood:\n{story}")
analysis_chain = (analysis_prompt | llm | StrOutputParser())

# Combine chains
story_with_analysis = story_chain | analysis_chain
# Chain goes like this: pipe | representing that output of left going to the right side as input to the next component
# In this case, the story generated by story_chain is passed as input to analysis_chain
# story_prompt | llm | StrOutputParser() | analysis_prompt | llm | StrOutputParser()

# Run the combined chain
story_analysis = story_with_analysis.invoke({"topic": "a rainy day in the city"})
print("\nAnalysis:", story_analysis)
# The output here will be the analysis of the story generated by the first chain.

