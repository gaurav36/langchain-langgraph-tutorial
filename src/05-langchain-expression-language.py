from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from global_llm_client import create_llm

# Create components
prompt = ChatPromptTemplate.from_template("Tell me a joke about {topic}")
llm = create_llm(max_output_tokens=512, temperature=0.8)
# String output parser to convert LLM output to plain string (instead of using response.content it will directly give the string)
output_parser = StrOutputParser()

# Chain them together using LCEL
chain = prompt | llm | output_parser # Basic sequential chain: Just prompt to LLM

print("Chain structure:")
print(chain)

# # Get input/output schema (useful for debugging)
print("\nInput schema:")
print(chain.input_schema.schema())

print("\nOutput schema:")
print(chain.output_schema.schema())

# Execute the workflow with a single call
result = chain.invoke({"topic": "AI"})
print(result)

# you can also transform the output using a lambda function after parsing it with StrOutputParser
chain_with_transformation = prompt | llm | StrOutputParser() | (lambda x: x.upper())
result = chain_with_transformation.invoke({"topic": "programming"})
print(result)

